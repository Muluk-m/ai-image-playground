#!/usr/bin/env python3
"""Regenerate the pinned, offline legacy upload protocol fixtures (local use only)."""
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
REVISION = "714c5f903db800081107750af5af4797645fcb19"
DEST = ROOT / "packages/shared/src/__tests__/fixtures"
DEST.mkdir(exist_ok=True)


def source(name):
    return subprocess.check_output(
        ["git", "show", f"{REVISION}:packages/shared/src/{name}.ts"],
        cwd=ROOT,
        text=True,
    )


header = (
    f"// Legacy protocol pinned to {REVISION}. Generated by scripts/generate-canvas-upload-legacy-fixtures.py.\n"
    "// Original implementation; only module paths and formatting are changed. Do not hand-edit.\n"
)
cloud = source("canvas-cloud")
cloud = cloud[cloud.index("export function isLocalCanvasFileId"):cloud.index("const finite =")]
cloud_path = DEST / "legacy-canvas-cloud.ts"
cloud_path.write_text(header + cloud)
conflicts = source("canvas-upload-conflicts").replace(
    "'./canvas-cloud'", "'./legacy-canvas-cloud'"
).replace("'./canvas-document'", "'../../canvas-document'")
conflicts_path = DEST / "legacy-canvas-upload-conflicts.ts"
conflicts_path.write_text(header + conflicts)
subprocess.run(
    ["pnpm", "exec", "biome", "check", "--write", str(cloud_path), str(conflicts_path)],
    cwd=ROOT,
    check=True,
)
