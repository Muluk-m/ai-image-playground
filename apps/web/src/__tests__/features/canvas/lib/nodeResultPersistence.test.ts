import { beforeEach, expect, it, vi } from 'vitest'
import * as Y from 'yjs'
import {
  pendingNodeResultImage,
  pendingNodeResults,
  persistLocalNodeResults,
  retryNodeResultStorage,
  subscribePendingNodeResults,
} from '../../../../features/canvas/lib/nodeResultPersistence'
import { DEFAULT_PARAMS } from '../../../../types'

const persist = vi.hoisted(() => vi.fn(async () => true))
vi.mock('../../../../store', () => ({ addCompletedCanvasTask: persist }))
beforeEach(() => persist.mockReset().mockResolvedValue(true))
it('retains generated bytes after storage failure and retries saving without regenerating', async () => {
  const doc = new Y.Doc(),
    notify = vi.fn()
  const stop = subscribePendingNodeResults(doc, notify)
  persist.mockResolvedValueOnce(false)
  const history = {
    id: 'local-job',
    prompt: 'tree',
    params: DEFAULT_PARAMS,
    images: ['data:image/png;base64,one', 'data:image/png;base64,two'],
  }
  await persistLocalNodeResults(doc, 'image', history)
  expect(pendingNodeResults(doc, 'image')).toBe(1)
  expect(pendingNodeResults(doc, 'other')).toBe(0)
  expect(notify).toHaveBeenCalledTimes(1)
  await retryNodeResultStorage(doc, 'image')
  expect(pendingNodeResults(doc, 'image')).toBe(0)
  expect(persist).toHaveBeenNthCalledWith(2, history)
  expect(notify).toHaveBeenCalledTimes(2)
  stop()
  doc.destroy()
})
it('shares in-flight retry work and isolates documents', async () => {
  const doc = new Y.Doc(),
    other = new Y.Doc()
  persist.mockResolvedValueOnce(false)
  await persistLocalNodeResults(doc, 'image', {
    id: 'job',
    prompt: '',
    params: DEFAULT_PARAMS,
    images: ['original'],
  })
  let finish!: (saved: boolean) => void
  persist.mockImplementationOnce(
    () =>
      new Promise((resolve) => {
        finish = resolve
      }),
  )
  const first = retryNodeResultStorage(doc, 'image'),
    second = retryNodeResultStorage(doc, 'image')
  expect(persist).toHaveBeenCalledTimes(2)
  expect(pendingNodeResults(other, 'image')).toBe(0)
  finish(true)
  await Promise.all([first, second])
  expect(pendingNodeResults(doc, 'image')).toBe(0)
  doc.destroy()
  other.destroy()
})

it('keeps pending originals and retry across reopening the same project', async () => {
  const first = new Y.Doc({ guid: 'account-a:project-a' })
  persist.mockResolvedValueOnce(false)
  await persistLocalNodeResults(first, 'image', {
    id: 'job',
    prompt: '',
    params: DEFAULT_PARAMS,
    images: ['original'],
  })
  first.destroy()
  const reopened = new Y.Doc({ guid: 'account-a:project-a' })
  const other = new Y.Doc({ guid: 'account-b:project-a' })
  expect(pendingNodeResults(reopened, 'image')).toBe(1)
  expect(pendingNodeResultImage(reopened, 'job', 0)).toBe('original')
  expect(pendingNodeResultImage(other, 'job', 0)).toBeUndefined()
  await retryNodeResultStorage(reopened, 'image')
  expect(pendingNodeResults(reopened, 'image')).toBe(0)
  reopened.destroy()
  other.destroy()
})
